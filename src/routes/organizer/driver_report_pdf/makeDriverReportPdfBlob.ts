import { jsPDF } from 'jspdf';
import { formatPhoneNumber } from '@src/lib/utils';

export type MakeDriverReportPdfBlobArguments = {
  driverFullName: string;
  driverEmail: string;
  driverPhone: string;
  referencePeriodString: string;
  deactivationPeriodString: string;
  totalNumberOfTrips: string;
  averageDailyPayString: string;
  grossEstimatedLostPay: string;
  grossEstimatedLostPayWithInterest: string;
  annualInterestRateAsString: string;
  deactivationPeriodDurationString: string;
  selectedEmployer?: string | null;
  interestPeriod: string;
  demandLetterDate?: string | null;
};

export default async (
  driverFullName: string,
  driverEmail: string,
  driverPhone: string,
  referencePeriodString: string,
  deactivationPeriodString: string,
  activitiesCountString: string,
  averageDailyPayString: string,
  grossEstimatedLostPay: string,
  grossEstimatedLostPayWithInterest: string,
  annualInterestRateAsString: string,
  selectedEmployer: string | undefined,
  interestPeriod: string,
  demandLetterDate: string | null
): Promise<Blob> => {
  const today = new Date();
  const formattedDate = today.toISOString().split('T')[0];
  const formattedPhone = formatPhoneNumber(driverPhone);

  const doc = new jsPDF({
    unit: 'in',
    format: [8.5, 11]
  });

  const LEFT_MARGIN = 0.5;

  doc.setFont('Helvetica', 'bold');
  doc.text('Earnings Report', LEFT_MARGIN, 1);

  doc.setFont('Helvetica', 'normal');
  doc.setFontSize(14);

  doc.text(formattedDate, 6.5, 1);

  doc.text(driverFullName, LEFT_MARGIN, 1.25);
  doc.text(formattedPhone, LEFT_MARGIN, 1.5);
  doc.text(driverEmail, LEFT_MARGIN, 1.75);

  doc.text('Reference period:', LEFT_MARGIN, 2.75);
  doc.text('Deactivation period:', LEFT_MARGIN, 3);
  doc.text('Total number of trips:', LEFT_MARGIN, 3.25);

  doc.text('Average daily pay:', LEFT_MARGIN, 3.75);
  doc.text('Gross estimated lost pay:', LEFT_MARGIN, 4);

  doc.text('Gross estimated lost pay with interest:', LEFT_MARGIN, 4.5);
  doc.text('Annual interest rate:', LEFT_MARGIN, 4.75);
  doc.text('Interest calculation period:', LEFT_MARGIN, 5);
  if (demandLetterDate) {
    doc.text('Demand/arbitration date:', LEFT_MARGIN, 5.25);
  }

  if (selectedEmployer) doc.text('Platform:', LEFT_MARGIN, 5.75);

  doc.setFont('Helvetica', 'bold');

  const CENTER_OFFSET = 4;
  doc.text(referencePeriodString, CENTER_OFFSET, 2.75);
  doc.text(deactivationPeriodString, CENTER_OFFSET, 3);
  doc.text(activitiesCountString, CENTER_OFFSET, 3.25);

  doc.text(averageDailyPayString, CENTER_OFFSET, 3.75);
  doc.text(grossEstimatedLostPay, CENTER_OFFSET, 4);
  doc.text(grossEstimatedLostPayWithInterest, CENTER_OFFSET, 4.5);
  doc.text(annualInterestRateAsString, CENTER_OFFSET, 4.75);
  doc.text(interestPeriod, CENTER_OFFSET, 5);
  if (demandLetterDate) {
    doc.text(demandLetterDate, CENTER_OFFSET, 5.25);
  }

  if (selectedEmployer) doc.text(selectedEmployer, CENTER_OFFSET, 5.75);

  doc.setFont('Helvetica', 'normal');
  doc.setFontSize(11);
  doc.text('Generated by System', LEFT_MARGIN, 10.5);

  const pdfBlob = doc.output('blob');

  return pdfBlob;
};
